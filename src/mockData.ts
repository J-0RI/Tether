/** [pain, walking days, mood], or null for a missed check-in */
type Row = [number, number, Mood] | null;

interface Extra {
  worse?: boolean;
  info?: boolean;
  help?: boolean;
  wants?: boolean;
  raw?: Partial<Record<QuestionKey, string>>;
  note?: string;
  redFlag?: string;
  followUp?: string;
}

const TIMES = [
  "9:12 AM",
  "7:48 PM",
  "10:30 AM",
  "6:05 PM",
  "8:21 AM",
  "12:40 PM",
  "4:15 PM",
  "8:55 PM",
];

/** Builds a check-in history, one every 14 days, oldest first. Negative extra keys count from the latest. */
function history(
  pid: string,
  channel: Channel,
  latestDaysAgo: number,
  rows: Row[],
  extras: Record<number, Extra> = {},
): CheckIn[] {
  return rows.map((row, i) => {
    const extra = extras[i] ?? extras[i - rows.length] ?? {};
    const base = {
      id: `${pid}-c${i + 1}`,
      date: daysAgo(latestDaysAgo + (rows.length - 1 - i) * 14),
      time: TIMES[(i + pid.length) % TIMES.length],
      channel,
    };
    if (!row) return { ...base, missed: true };
    const [pain, walk, mood] = row;
    return {
      ...base,
      answers: {
        worse: extra.worse ?? false,
        pain,
        walk,
        mood,
        info: extra.info ?? true,
        help: extra.help ?? false,
        wants: extra.wants ?? true,
      },
      raw: extra.raw,
      note: extra.note,
      redFlag: extra.redFlag,
      followUp: extra.followUp,
    };
  });
}

type Spec =
  | ReadinessState
  | [ReadinessState, number]
  | [ReadinessState, number | null, string];

function readiness(spec: Partial<Record<ReadinessKey, Spec>>): ReadinessItem[] {
  return READINESS_ITEMS.map(({ key }) => {
    const s = spec[key] ?? "notdue";
    if (typeof s === "string") return { key, state: s };
    const [state, ago, detail] = s;
    return { key, state, date: ago == null ? undefined : daysAgo(ago), detail };
  });
}

function activity(
  pid: string,
  entries: [number, ActivityEntry["kind"], string][],
): ActivityEntry[] {
  return entries.map(([ago, kind, text], i) => ({
    id: `${pid}-a${i}`,
    at: new Date(
      parseDate(daysAgo(ago)).getTime() + (10 + i) * 3_600_000,
    ).toISOString(),
    kind,
    text,
    by: NURSE,
  }));
}

